#!/usr/bin/env python3
"""Case-level method x system interaction tests for full-coverage pairs.

Consumes the three-method full-coverage long table generated by
`multiverse_pair_analysis.py` and fits, for one or more method pairs:

  full:    correct ~ C(method) * C(system_id)
  reduced: correct ~ C(method) + C(system_id)

The likelihood-ratio test compares full vs reduced and is interpreted as a
case-level method x system interaction diagnostic. Cluster-robust SEs by
case_id are used for coefficient summaries; the LRT itself uses model
log-likelihoods, matching the existing interaction test scripts.
"""
from __future__ import annotations

import argparse
import itertools
import json
import warnings
from pathlib import Path

import pandas as pd
import statsmodels.api as sm
import statsmodels.formula.api as smf
from scipy.stats import chi2

DEFAULT_REPO_ROOT = Path("$HOME/mnt/3090/auditstack")
DEFAULT_INPUT = DEFAULT_REPO_ROOT / "results_stats" / "multiverse_full_coverage" / "full_coverage_long.csv"
DEFAULT_OUTPUT_DIR = DEFAULT_REPO_ROOT / "results_stats" / "interaction_full_coverage"
FULL_METHODS = ["baro", "z_family", "alertcount"]


def _fit_glm(df: pd.DataFrame, formula: str):
    return smf.glm(
        formula,
        data=df,
        family=sm.families.Binomial(),
    ).fit(cov_type="cluster", cov_kwds={"groups": df["case_id"]})


def _fit_null(df: pd.DataFrame) -> float:
    return float(_fit_glm(df, "correct ~ 1").llf)


def _mcfadden_r2(llf: float, llf_null: float) -> float:
    return float(1.0 - llf / llf_null)


def _wald_for_prefix(model, prefix: str) -> float:
    names = [n for n in model.params.index if n.startswith(prefix)]
    if not names:
        return float("nan")
    return float(model.wald_test(names, scalar=True).pvalue)


def run_pair(df: pd.DataFrame, method_a: str, method_b: str) -> dict:
    sub = df[df["method"].isin([method_a, method_b])].copy()
    sub["correct"] = sub["correct"].clip(0.0, 1.0).astype(float)
    cov = sub.groupby(["method", "system_id"]).size().unstack(fill_value=0)
    if cov.shape != (2, 11) or not (cov.values > 0).all():
        raise RuntimeError(f"{method_a} vs {method_b}: expected complete 2x11 block, got\n{cov}")

    warn_log: list[str] = []
    with warnings.catch_warnings(record=True) as wlist:
        warnings.simplefilter("always")
        full = _fit_glm(sub, "correct ~ C(method) * C(system_id)")
        reduced = _fit_glm(sub, "correct ~ C(method) + C(system_id)")
        for w in wlist:
            warn_log.append(f"{w.category.__name__}: {w.message}")
    warn_log.append(f"full converged={bool(getattr(full, 'converged', True))}")
    warn_log.append(f"reduced converged={bool(getattr(reduced, 'converged', True))}")

    llf_full = float(full.llf)
    llf_reduced = float(reduced.llf)
    df_full = int(len(full.params))
    df_reduced = int(len(reduced.params))
    df_diff = df_full - df_reduced
    lrt = 2.0 * (llf_full - llf_reduced)
    p_interaction = float(1.0 - chi2.cdf(lrt, df_diff))
    llf_null = _fit_null(sub)

    params = full.params
    bse = full.bse
    coef_rows = []
    for name in params.index:
        coef_rows.append({
            "term": str(name),
            "coef": float(params[name]),
            "std_err": float(bse[name]),
            "z": float(params[name] / bse[name]),
            "p_value": float(full.pvalues[name]),
        })

    return {
        "method_a": method_a,
        "method_b": method_b,
        "n_obs": int(len(sub)),
        "n_cases": int(sub["case_id"].nunique()),
        "n_systems": int(sub["system_id"].nunique()),
        "coverage_matrix": cov.to_dict(),
        "llf_with_interaction": llf_full,
        "llf_without_interaction": llf_reduced,
        "df_full_model_params": df_full,
        "df_reduced_model_params": df_reduced,
        "lrt_statistic": float(lrt),
        "df_interaction_terms": int(df_diff),
        "p_interaction": p_interaction,
        "mcfadden_r2_full": _mcfadden_r2(llf_full, llf_null),
        "mcfadden_r2_reduced": _mcfadden_r2(llf_reduced, llf_null),
        "main_effect_method_p_reduced_model": _wald_for_prefix(reduced, "C(method)"),
        "main_effect_system_p_reduced_model": _wald_for_prefix(reduced, "C(system_id)"),
        "p_interaction_wald_on_full_model": _wald_for_prefix(full, "C(method)"),
        "coef_table_full_model": coef_rows,
        "convergence_warnings": warn_log,
        "interpretation": "PASS (p<0.05)" if p_interaction < 0.05 else "FAIL (p>=0.05)",
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input-long", type=Path, default=DEFAULT_INPUT)
    ap.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    ap.add_argument(
        "--pair",
        action="append",
        default=[],
        help="Method pair as method_a,method_b. Repeatable. Default: z_family,alertcount.",
    )
    args = ap.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(args.input_long)
    pairs = []
    if args.pair:
        for spec in args.pair:
            a, b = [x.strip() for x in spec.split(",", 1)]
            pairs.append((a, b))
    else:
        pairs = [("z_family", "alertcount")]

    rows = []
    payload = {
        "input_long": str(args.input_long),
        "model_spec": "correct ~ C(method) * C(system_id), GLM-Binomial, cluster SE by case_id",
        "pairs": {},
    }
    for method_a, method_b in pairs:
        res = run_pair(df, method_a, method_b)
        key = f"{method_a}_vs_{method_b}"
        payload["pairs"][key] = res
        rows.append({
            "method_a": method_a,
            "method_b": method_b,
            "n_obs": res["n_obs"],
            "n_cases": res["n_cases"],
            "n_systems": res["n_systems"],
            "lrt_statistic": res["lrt_statistic"],
            "df_interaction_terms": res["df_interaction_terms"],
            "p_interaction": res["p_interaction"],
            "mcfadden_r2_full": res["mcfadden_r2_full"],
            "mcfadden_r2_reduced": res["mcfadden_r2_reduced"],
            "interpretation": res["interpretation"],
        })

    out_json = args.output_dir / "interaction_pair_tests.json"
    out_csv = args.output_dir / "interaction_pair_tests.csv"
    with open(out_json, "w") as f:
        json.dump(payload, f, indent=2, default=float)
    pd.DataFrame(rows).to_csv(out_csv, index=False)
    print(f"[written] {out_json}")
    print(f"[written] {out_csv}")
    print(pd.DataFrame(rows).to_string(index=False))


if __name__ == "__main__":
    main()

